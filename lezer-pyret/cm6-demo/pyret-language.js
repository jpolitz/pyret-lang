// CM6 LanguageSupport for Pyret, backed by the Lezer grammar that REPLAYS
// Pyret's own tokenizer (see lezer-pyret/PLAN.md, lezer-run.js).
//
// The grammar uses an EXTERNAL tokenizer that, instead of scanning characters,
// reads a pre-built map (CUR) from absolute char position -> Lezer term id.
// We tokenize the whole document with Pyret's tokenizer up front, tile the
// whitespace/comment gaps as `Space`, then drive the inner LR parser. The CM6
// language is wired by overriding the parser's `createParse` to (re)build CUR
// from the current document before each parse.
import {
  LRLanguage, LanguageSupport, indentNodeProp, foldNodeProp,
  indentUnit, syntaxHighlighting, HighlightStyle,
} from "@codemirror/language";
import { styleTags, tags as t } from "@lezer/highlight";
// PRE-BUILT parser table (generated by gen-table.js) + its term ids. This ships
// only the @lezer/lr runtime — NOT @lezer/generator — and does no grammar
// compilation at page load.
import { parser as baseParser } from "./pyret-parser.gen.js";
import * as TERMS from "./pyret-terms.gen.js";
import { PS } from "./parse-state.js";
import { tokenize } from "./pyret-tokenizer.js";

const san = (n) => n.replace(/-/g, "_");

// Tile a Pyret token array into the CUR map, filling gaps (ws/comments) as Space.
function tile(tokens, len) {
  const map = new Map();
  let prev = 0;
  for (let i = 0; i < tokens.length; i++) {
    const tk = tokens[i];
    if (tk.name === "EOF") break;
    const s = tk.startChar, e = tk.endChar;
    if (s > prev) map.set(prev, { e: s, term: TERMS.Space });
    const term = TERMS[san(tk.name)];
    map.set(s, { e, term: term === undefined ? null : term, value: tk.value });
    prev = e;
  }
  if (prev < len) map.set(prev, { e: len, term: TERMS.Space });
  return map;
}

