// ---- folding: hide block bodies, keep the header + closing token visible ----
function blockFold(node, state) {
  const from = state.doc.lineAt(node.from).to;        // end of the header line
  const last = node.lastChild;                         // END / RBRACE / RPAREN
  const to = last ? last.from : node.to;
  return to > from ? { from, to } : null;
}
const FOLDABLE =
  "Fun_expr Lambda_expr Method_expr Data_expr Cases_expr If_expr If_pipe_expr " +
  "When_expr For_expr Check_expr User_block_expr Multi_let_expr Letrec_expr " +
  "Type_let_expr Reactor_expr Table_expr Spy_stmt Block " +
  "Table_select Table_filter Table_order Table_extract Table_update Table_extend " +
  "Load_table_expr Obj_expr Tuple_expr Record_ann";
const folds = foldNodeProp.add(
  Object.fromEntries(FOLDABLE.split(/\s+/).map((n) => [n, blockFold]))
);

// ---- indentation: CPO-style. Indent a block's body one unit past the line the
// block opens on; dedent the closing token (end / else / sharing: / where: / } ] ))
// back to the opener's indent. (delimitedIndent mis-counted on this grammar.)
const CLOSERS = /^\s*(end\b|else if\b|else\b|sharing:|where:|\}|\]|\))/;
const blockIndent = (cx) => {
  // If the current line is this node's OWN opening line, we have no opinion —
  // let the enclosing block decide where the node itself sits.
  if (cx.state.doc.lineAt(cx.node.from).number === cx.state.doc.lineAt(cx.pos).number) {
    return null;
  }
  const base = cx.lineIndent(cx.node.from);                 // opener line's indent
  return CLOSERS.test(cx.textAfter) ? base : base + cx.unit; // closer dedents; body +1 unit
};
const BLOCK_NODES =
  "Fun_expr Lambda_expr Method_expr Data_expr Cases_expr If_expr If_pipe_expr " +
  "When_expr For_expr Check_expr User_block_expr Multi_let_expr Letrec_expr " +
  "Type_let_expr Reactor_expr Table_expr Spy_stmt Table_select Table_filter " +
  "Table_order Table_extract Table_update Table_extend Load_table_expr " +
  "Obj_expr Tuple_expr Record_ann " +
  // method-as-field bodies (data variants / objects), the with:/sharing: field
  // blocks, and where:/test blocks
  "Field Obj_field Data_with Data_sharing Where_clause";
const indents = indentNodeProp.add(
  Object.fromEntries(BLOCK_NODES.split(/\s+/).map((n) => [n, blockIndent]))
);

const configured = baseParser.configure({ props: [styles, folds, indents] });

// ---- wrap as a CM6 language; override createParse to (re)tile per document --
const pyretLanguage = LRLanguage.define({
  parser: configured,
  languageData: {
    commentTokens: { line: "#", block: { open: "#|", close: "|#" } },
    // auto-reindent the current line as soon as it becomes a dedent token
    indentOnInput: /^\s*(end|else if|else|sharing:|where:|\||\}|\]|\))$/,
  },
});

// Patch the configured parser instance used by the language: build CUR from the
// full current document, then delegate. We drop `fragments` to force a full
// reparse (the replay tokenizer is not incremental-aware in this demo).
const inner = pyretLanguage.parser.createParse.bind(pyretLanguage.parser);
pyretLanguage.parser.createParse = (input, fragments, ranges) => {
  const text = input.read(0, input.length);
  try {
    PS.CUR = tile(tokenize(text), text.length);
  } catch (e) {
    PS.CUR = new Map(); // tokenizer failed (e.g. unterminated string) -> error nodes
  }
  return inner(input, [], ranges);
};

