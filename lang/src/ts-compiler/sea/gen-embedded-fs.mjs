#!/usr/bin/env node
/*
  Build-time generator: emit sea/embedded-fs.generated.ts, which bun bakes into
  the self-contained binary. It embeds every *compiler-fixed* source the compile
  path reads off disk, keyed by its repo-root-relative POSIX path:

    - the builtin trove sources it compiles (src/arr/trove, src/js/trove)
    - the standalone template (src/js/base/handalone.js)
    - the require-config (src/scripts/standalone-configA.json) and the runtime
      JS it concatenates (build/phaseA/js/*, lib/jglr/*)
    - the runtime deps bundle + default config (build/ts-compiler/*)

  The values are `type: "text"` imports so bun embeds them as blobs. The runtime
  shim (embedded-fs.ts) serves these only as a fallback when the file is absent
  on disk, so a checkout present on disk always wins (byte-exact) and the binary
  self-contains when it isn't.

  Run from lang/. Requires `make ts-compiler` to have produced build/ts-compiler
  and build/phaseA/js.
*/
import * as fs from 'fs';
import * as path from 'path';

const lang = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..', '..');
const seaDir = path.join(lang, 'src', 'ts-compiler', 'sea');
const outFile = path.join(seaDir, 'embedded-fs.generated.ts');

// Collect *.ext files under a repo-relative dir, recursively.
function collect(relDir, ext, into) {
  const abs = path.join(lang, relDir);
  if (!fs.existsSync(abs)) throw new Error(`missing ${relDir} (run 'make ts-compiler' first)`);
  for (const name of fs.readdirSync(abs).sort()) {
    const rel = path.posix.join(relDir, name);
    const st = fs.statSync(path.join(lang, rel));
    if (st.isDirectory()) collect(rel, ext, into);
    else if (name.endsWith(ext)) into.push(rel);
  }
}

const keys = [];
collect('src/arr/trove', '.arr', keys);
collect('src/js/trove', '.js', keys);

// Precompiled builtins (the `global` closure), if present: a read-only compile
// cache shipped in the binary so first runs skip recompiling the trove ("no
// Compiling N/M"). Keyed under build/ts-compiler/lib-precompiled/, which the
// friendly CLI passes as --compiled-read-only-dir; the sea provider reports a
// positive mtime for these keys so cachedAvailable accepts them. Excludes any
// seed-program cache entry (names containing ".arr-").
const precompiledDir = 'build/ts-compiler/lib-precompiled';
if (fs.existsSync(path.join(lang, precompiledDir))) {
  for (const name of fs.readdirSync(path.join(lang, precompiledDir)).sort()) {
    if (name.endsWith('.js') && !name.includes('.arr-')) {
      keys.push(path.posix.join(precompiledDir, name));
    }
  }
}

// Individually-named fixed files (config raw-js targets + templates + bundle).
const rawJs = [
  'codePoint', 'exn-stack-parser', 'js-numbers', 'namespace', 'pyret-parser',
  'pyret-tokenizer', 'runtime', 'runtime-util', 'type-util', 'secure-loader',
  'post-load-hooks',
].map((n) => `build/phaseA/js/${n}.js`);

const named = [
  'src/js/base/handalone.js',
  'src/scripts/standalone-configA.json',
  'lib/jglr/jglr.js',
  'lib/jglr/rnglr.js',
  'lib/jglr/cyclicJSON.js',
  'build/ts-compiler/bundled-node-deps.js',
  'build/ts-compiler/config.json',
  ...rawJs,
];
for (const rel of named) {
  if (!fs.existsSync(path.join(lang, rel))) throw new Error(`missing ${rel} (run 'make ts-compiler' first)`);
  keys.push(rel);
}

// Emit: one text import per file, then a key -> value map.
let imports = '';
let entries = '';
keys.forEach((rel, i) => {
  const importPath = path.posix.join('..', '..', '..', rel); // from sea/ to lang/
  imports += `import _${i} from ${JSON.stringify(importPath)} with { type: 'text' };\n`;
  entries += `  ${JSON.stringify(rel)}: _${i} as unknown as string,\n`;
});

const banner = `// AUTO-GENERATED by gen-embedded-fs.mjs — do not edit. ${keys.length} files.\n`;
const body =
  banner +
  imports +
  `\nexport const EMBEDDED_FS: Record<string, string> = {\n${entries}};\n`;

fs.writeFileSync(outFile, body);
console.log(`embedded-fs.generated.ts: ${keys.length} files embedded`);
